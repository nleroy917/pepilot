"""The `run:` script every job gets: all jobs' commands, of which each runs its own share.

One script for all jobs, because SkyPilot submits the N jobs (`--num-jobs N`) from one task; a
job finds its share by `$SKYPILOT_JOB_RANK`. It needs nothing but bash on the instance.

Each sample's commands go to a file through a quoted heredoc, so they arrive exactly as
rendered (no expansion), and run in their own `bash -euo pipefail`: any failing command fails
the sample, an unset variable is an error, and a failure inside a pipe is not hidden. A failed
sample does not stop the job's other samples; the job fails at the end if any did.
"""

from __future__ import annotations

import shlex
from typing import Sequence

from pepilot.plan import SampleRun

HEREDOC_END = "__PEPILOT_EOF__"

_PRELUDE = """\
# Generated by pepilot {version}. Job $SKYPILOT_JOB_RANK runs the samples in its arm below,
# one after another, each in its own `bash -euo pipefail`, and fails if any of them failed.
pepilot_dir=$(mktemp -d)
trap 'rm -rf "$pepilot_dir"' EXIT
pepilot_names=()
pepilot_add() {{
  cat >"$pepilot_dir/${{#pepilot_names[@]}}.sh"
  pepilot_names+=("$1")
}}
pepilot_rank=${{SKYPILOT_JOB_RANK:-0}}

case "$pepilot_rank" in
"""

_LOOP = """\
  *)
    echo "pepilot: job $pepilot_rank has no samples (this script has {n_jobs} jobs)" >&2
    exit 1
    ;;
esac

pepilot_n=${#pepilot_names[@]}
pepilot_failed=()
echo "pepilot: job $pepilot_rank of ${SKYPILOT_NUM_JOBS:-1}: $pepilot_n sample(s)"
for pepilot_i in "${!pepilot_names[@]}"; do
  pepilot_sample=${pepilot_names[$pepilot_i]}
  pepilot_tag="[$((pepilot_i + 1))/$pepilot_n] $pepilot_sample"
  echo "pepilot: $pepilot_tag: started"
  pepilot_start=$SECONDS
  if PEPILOT_SAMPLE="$pepilot_sample" bash -euo pipefail "$pepilot_dir/$pepilot_i.sh"; then
    echo "pepilot: $pepilot_tag: succeeded in $((SECONDS - pepilot_start))s"
  else
    echo "pepilot: $pepilot_tag: FAILED with exit code $? after $((SECONDS - pepilot_start))s" >&2
    pepilot_failed+=("$pepilot_sample")
  fi
done

if [ "${#pepilot_failed[@]}" -gt 0 ]; then
  echo "pepilot: ${#pepilot_failed[@]} of $pepilot_n sample(s) failed: ${pepilot_failed[*]}" >&2
  exit 1
fi
echo "pepilot: all $pepilot_n sample(s) succeeded"
"""


def run_script(jobs: Sequence[Sequence[SampleRun]]) -> str:
    """The `run:` section for these jobs (job k is `SKYPILOT_JOB_RANK=k`)."""
    from pepilot import __version__

    if not jobs:
        raise ValueError("no jobs to write a script for")
    parts = [_PRELUDE.format(version=__version__)]
    for rank, job in enumerate(jobs):
        parts.append(f"  {rank})\n")
        for run in job:
            body = run.command if run.command.endswith("\n") else run.command + "\n"
            if HEREDOC_END in body.splitlines():
                raise ValueError(f"sample {run.name!r}: its command contains the line {HEREDOC_END}")
            parts.append(f"    pepilot_add {shlex.quote(run.name)} <<'{HEREDOC_END}'\n{body}{HEREDOC_END}\n")
        parts.append("    ;;\n")
    parts.append(_LOOP.replace("{n_jobs}", str(len(jobs))))
    return "".join(parts)
